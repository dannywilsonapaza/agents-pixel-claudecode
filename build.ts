// node build.ts → dist/pixel-office.js (daemon + UI in one self-contained file)

import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";

const web = await build({
  entryPoints: ["web/main.ts"],
  bundle: true,
  format: "iife",
  target: "es2020",
  minify: true,
  write: false,
  legalComments: "none",
});
const js = web.outputFiles[0].text;

// the font ships inside the page as a data URL, so the UI never contacts a font CDN
const font = (await readFile("web/fonts/PixelifySans-latin.woff2")).toString("base64");
const fontRef = 'url("fonts/PixelifySans-latin.woff2")';
const page = await readFile("web/index.html", "utf8");
if (!page.includes(fontRef)) throw new Error("web/index.html: @font-face source not found");
const html = page.replace(fontRef, `url(data:font/woff2;base64,${font})`);

await writeFile(
  "src/assets.generated.ts",
  `// generated by build.ts — do not edit\nexport const HTML = ${JSON.stringify(html)};\nexport const JS = ${JSON.stringify(js)};\n`,
);

await build({
  entryPoints: ["src/claude/main.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  outfile: "dist/pixel-office.js",
  banner: { js: "// claudecode-pixel-office — live pixel-art office for Claude Code agents" },
  legalComments: "none",
});

console.log(`built dist/pixel-office.js (web ${(js.length / 1024).toFixed(1)} KiB)`);
